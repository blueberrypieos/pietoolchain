"""
    dtrace-h.py PROVIDER.d PROVIDER.h
"""
import re
import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = re.sub(r"/\*.*?\*/", "", open(src).read(), flags=re.S)
    lines = [f"/* Generated by dtrace-h.py from {src.rsplit('/', 1)[-1]}: probes compiled out. */"]
    guard = "_" + re.sub(r"\W", "_", out.rsplit("/", 1)[-1]).upper()
    lines += [f"#ifndef {guard}", f"#define {guard}", ""]
    for prov, body in re.findall(r"provider\s+(\w+)\s*\{(.*?)\}\s*;", text, re.S):
        for name, args in re.findall(r"probe\s+(\w+)\s*\((.*?)\)\s*;", body, re.S):
            n = len([a for a in args.split(",") if a.strip() and a.strip() != "void"])
            macro = f"{prov}_{name}".upper().replace("__", "_")
            params = ", ".join(f"arg{i}" for i in range(n))
            uses = " ".join(f"(void)(arg{i});" for i in range(n))
            lines.append(f"#define {macro}({params}) do {{ {uses} }} while (0)".replace("{  }", "{ }"))
            lines.append(f"#define {macro}_ENABLED() (0)")
    lines += ["", f"#endif /* {guard} */", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
