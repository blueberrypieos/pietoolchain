import os
import re
import sys

PLATFORM_IDS = {"MACOSX": (1, "macOS"), "IOS": (2, "iOS"), "TVOS": (3, "tvOS"),
                "WATCHOS": (4, "watchOS"), "BRIDGEOS": (5, "bridgeOS"), "XROS": (11, "xrOS")}

PLATFORMS = {
    "MACOSX":   [(10, range(0, 17)), *[(m, range(0, 8)) for m in range(11, 16)], (26, range(0, 10))],
    "IOS":      [*[(m, range(0, 8)) for m in range(2, 19)], (26, range(0, 10))],
    "TVOS":     [*[(m, range(0, 8)) for m in range(9, 19)], (26, range(0, 10))],
    "WATCHOS":  [*[(m, range(0, 8)) for m in range(1, 12)], (26, range(0, 10))],
    "BRIDGEOS": [(m, range(0, 8)) for m in range(1, 11)],
    "XROS":     [*[(m, range(0, 8)) for m in range(1, 3)], (26, range(0, 10))],
}


def v(major, minor=0):
    return major << 16 | minor << 8


NEW_SETS = [("fall_2024", 0x07e80901, v(15), v(18), v(18), v(11), v(2), v(9), v(24))]
for i, letter in enumerate("BCDEFG", 1):
    NEW_SETS.append(("2024_SU_" + letter, 0x07e80b01 + (i << 8), v(15, i), v(18, i), v(18, i),
                     v(11, i), v(2, i), v(9, i), v(24, i)))
NEW_SETS.append(("fall_2025", 0x07e90901, v(26), v(26), v(26), v(26), v(26), v(10), v(25)))
for i, letter in enumerate("BCDEF", 1):
    NEW_SETS.append(("2025_SU_" + letter, 0x07e90b01 + (i << 8), v(26, i), v(26, i), v(26, i),
                     v(26, i), v(26, i), v(10, i), v(25, i)))


def version_sets(incdir):
    sets = []
    inc = os.path.join(incdir, "for_dyld_priv.inc") if incdir else None
    if inc and os.path.exists(inc):
        for m in re.finditer(r"#define (dyld_\w+_os_versions)\s+\(\{ \(dyld_build_version_t\)"
                             r"\{0xffffffff, (0x[0-9a-fA-F]+)\}", open(inc).read()):
            sets.append((m.group(1), int(m.group(2), 16)))
    known = {n for n, _ in sets}
    for e in NEW_SETS:
        name = "dyld_%s_os_versions" % e[0]
        if name not in known:
            sets.append((name, e[1]))
    return sets


def extend_version_map(incdir):
    path = os.path.join(incdir, "VersionMap.h")
    if not os.path.exists(path):
        return
    text = open(path).read()
    entries = re.findall(r"\t\{ \.set = .*? \}", text)
    have = {int(re.search(r"\.set = (0x[0-9a-fA-F]+)", e).group(1), 16) for e in entries}
    for (_, st, mac, ios, tv, watch, vision, bridge, dk) in NEW_SETS:
        if st not in have:
            entries.append("\t{ .set = 0x%09x, .bridgeos = 0x%08x, .driverkit = 0x%08x, .ios = 0x%08x, "
                           ".macos = 0x%08x, .tvos = 0x%08x, .visionos = 0x%08x, .watchos = 0x%08x }"
                           % (st, bridge, dk, ios, mac, tv, vision, watch))
    start = text.index("static const std::array<VersionSetEntry")
    end = text.index("}};", start) + 3
    table = ("static const std::array<VersionSetEntry, %d> sVersionMap = {{\n%s\n}};"
             % (len(entries), ",\n".join(entries)))
    with open(path, "w") as f:
        f.write(text[:start] + table + text[end:])


def main():
    incdir = sys.argv[2] if len(sys.argv) > 2 else None
    out = ["/* Generated by dyld-version-defines.py. */",
           "#ifndef _MACH_O_DYLD_VERSION_DEFINES_H_",
           "#define _MACH_O_DYLD_VERSION_DEFINES_H_", ""]
    for plat, rels in PLATFORMS.items():
        for major, minors in rels:
            for minor in minors:
                v = major << 16 | minor << 8
                pid, pname = PLATFORM_IDS[plat]
                out.append("#define DYLD_%s_VERSION_%d_%d 0x%08x" % (plat, major, minor, v))
                out.append("#define dyld_platform_version_%s_%d_%d ((dyld_build_version_t){ %d, 0x%08x })"
                           % (pname, major, minor, pid, v))
        out.append("")
    for name, value in version_sets(incdir):
        out.append("#define %s ({ (dyld_build_version_t){0xffffffff, 0x%09x}; })" % (name, value))
    out += ["", "#endif /* _MACH_O_DYLD_VERSION_DEFINES_H_ */", ""]
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out))
    if incdir:
        extend_version_map(incdir)


if __name__ == "__main__":
    main()
