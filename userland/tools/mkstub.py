"""
    mkstub.py EXPORTS OUT.s
"""
import sys


def main():
    exports, out = sys.argv[1], sys.argv[2]
    syms = []
    for line in open(exports):
        line = line.split("#", 1)[0].strip()
        if line:
            syms.append(line)
    with open(out, "w") as f:
        f.write(f"// Generated by mkstub.py from {exports}\n\t.text\n\t.p2align 2\n")
        for s in sorted(set(syms)):
            f.write(f"\t.globl {s}\n{s}:\n\tbrk #1\n")


if __name__ == "__main__":
    main()
